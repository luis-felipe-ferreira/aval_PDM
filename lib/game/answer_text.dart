class AnswerText {
  AnswerText._();

  static bool isLetter(String character) =>
      RegExp(r'^[A-Za-zÀ-ÖØ-öø-ÿ]$').hasMatch(character);

  static String normalize(String character) {
    final upper = character.toUpperCase();
    const accents = {
      'Á': 'A',
      'À': 'A',
      'Â': 'A',
      'Ã': 'A',
      'Ä': 'A',
      'É': 'E',
      'È': 'E',
      'Ê': 'E',
      'Ë': 'E',
      'Í': 'I',
      'Ì': 'I',
      'Î': 'I',
      'Ï': 'I',
      'Ó': 'O',
      'Ò': 'O',
      'Ô': 'O',
      'Õ': 'O',
      'Ö': 'O',
      'Ú': 'U',
      'Ù': 'U',
      'Û': 'U',
      'Ü': 'U',
      'Ç': 'C',
    };
    return accents[upper] ?? upper;
  }
}
